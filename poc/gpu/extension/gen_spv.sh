#!/bin/bash
# Regenerates pip_bvh_spv.h (the SPIR-V of the MP12c point-in-solid filter kernel) from gpu_src/pip_bvh.comp. Needs glslc (Vulkan SDK). Provenance: exactmesh gpu/pip_bvh.comp,
# pip_filter.inc, orient_filter.inc (Apache-2.0) and gpu/shaders/f64soft.inc (derived from MongoDB's DoubleDoubleSummation, SSPL-1.0), copied at exactmesh commit b9a6590 or later.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"; GLSLC="${GLSLC:-$HOME/VulkanSDK/1.3.283.0/macOS/bin/glslc}"
"$GLSLC" --target-env=vulkan1.2 -O0 -I "$HERE/gpu_src" -o /tmp/pip_bvh.spv "$HERE/gpu_src/pip_bvh.comp"
python3 - "$HERE" <<'PY'
import struct,sys
d=open('/tmp/pip_bvh.spv','rb').read(); w=struct.unpack('<%dI'%(len(d)//4),d)
out=['// Generated by gen_spv.sh from gpu_src/pip_bvh.comp (glslc --target-env=vulkan1.2 -O0). SPIR-V is portable; do not edit.','#pragma once','#include <cstdint>','#include <cstddef>','static const uint32_t kPipBvhSpv[] = {']
for i in range(0,len(w),8): out.append('    '+', '.join('0x%08x'%x for x in w[i:i+8])+',')
out.append('};'); out.append('static const size_t kPipBvhSpvWords = %d;'%len(w))
open(sys.argv[1]+'/pip_bvh_spv.h','w').write('\n'.join(out)+'\n')
PY
